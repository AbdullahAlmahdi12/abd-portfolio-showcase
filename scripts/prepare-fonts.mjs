import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const defaultRoot = fileURLToPath(new URL("../", import.meta.url));
const weights = [["Light", "300"], ["Regular", "400"], ["Medium", "500"], ["Bold", "700"], ["Black", "900"]];

/** @param {string} projectRoot */
export function prepareArabicFont(projectRoot = defaultRoot) {
  const present = weights.map(([name]) => existsSync(resolve(projectRoot, `.amp/in/private-fonts/thmanyah/thmanyahsans-${name}.otf`)));
  if (present.some(Boolean) && !present.every(Boolean)) {
    throw new Error("The private Thmanyah font set is incomplete. Supply Light, Regular, Medium, Bold and Black, or remove the partial set to use the public fallback.");
  }

  const useThmanyah = present.every(Boolean);
  const src = useThmanyah
    ? `[\n${weights.map(([name, weight]) => `    {path: "../../.amp/in/private-fonts/thmanyah/thmanyahsans-${name}.otf", weight: "${weight}"},`).join("\n")}\n  ]`
    : '"../../public/fonts/noto-sans-arabic/NotoSansArabic-Variable.ttf"';
  const source = `// Generated by scripts/prepare-fonts.mjs; do not commit this file.
import localFont from "next/font/local";

export const arabic = localFont({
  src: ${src},
  variable: "--font-arabic", ${useThmanyah ? "" : 'weight: "100 900", '}display: "swap", preload: false,
});
`;
  const output = resolve(projectRoot, "src/app/arabic-font.generated.ts");
  mkdirSync(dirname(output), { recursive: true });
  if (!existsSync(output) || readFileSync(output, "utf8") !== source) writeFileSync(output, source);
  return useThmanyah ? "Thmanyah" : "Noto Sans Arabic (fallback)";
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(`Arabic font prepared: ${prepareArabicFont(process.argv[2] ? resolve(process.argv[2]) : defaultRoot)}`);
}
